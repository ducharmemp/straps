local root = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h')
vim.opt.rtp:prepend(root)
package.path = root .. '/lua/?.lua;' .. root .. '/lua/?/init.lua;' .. package.path
local straps = require('straps').setup({ session_dir = vim.fn.tempname(), terminal_status = false })
local ui, state = require('straps.ui'), require('straps.state')
local api = vim.api
local ns = api.nvim_create_namespace('straps.since_you_left')
local counter = tonumber(vim.env.STRAPS_DIVIDER_COUNTERFACTUAL)

local function check(id, condition)
  if counter == id then condition = not condition end
  assert(condition, 'divider assertion ' .. id)
end

local function marks(buf)
  return api.nvim_buf_get_extmarks(buf, ns, 0, -1, { details = true })
end

local function view(win)
  return api.nvim_win_call(win, vim.fn.winsaveview)
end

local function open()
  local buf = ui.open_session('none', { explicit_split = true })
  vim.wo.foldenable = false
  state.append(buf, 'user', nil, ('history\n'):rep(55) .. 'previous line')
  vim.cmd('normal! Gzt')
  vim.cmd('redraw')
  return buf, api.nvim_get_current_win()
end

local function elsewhere(win)
  vim.cmd('vnew')
  local other = api.nvim_get_current_win()
  api.nvim_set_current_win(win)
  vim.cmd('redraw')
  local before = view(win)
  api.nvim_set_current_win(other)
  return before
end

after_each(function()
  vim.cmd('only!')
  vim.cmd('enew!')
  straps.setup({ render = true })
end)

it('anchors above the first new block, keeps the view, and clears on cursor passage', function()
  local buf, win = open()
  state.append(buf, 'assistant', nil, 'while reading')
  check(1, #marks(buf) == 0)
  local before = elsewhere(win)
  local tail = api.nvim_buf_line_count(buf)
  state.append(buf, 'tool_result', { id = 'example' }, 'first result')
  local m = marks(buf)[1] or {}
  check(2, m[2] == tail + 1 and m[4].virt_lines_above and m[4].virt_lines[1][1][1] == '── since you left ──')
  state.append(buf, 'assistant', nil, 'second result')
  state.ensure_trailing_user(buf)
  check(3, vim.deep_equal(marks(buf), { m }))
  ui.show_session(buf, 'none')
  check(4, vim.deep_equal(view(win), before))
  check(5, #marks(buf) == 1)
  local text, tick, modified = state.transcript_lines(buf), api.nvim_buf_get_changedtick(buf), vim.bo[buf].modified
  api.nvim_win_set_cursor(win, { m[2] + 1, 0 })
  api.nvim_exec_autocmds('CursorMoved', { buffer = buf })
  check(6, #marks(buf) == 1)
  api.nvim_win_set_cursor(win, { m[2] + 2, 0 })
  api.nvim_exec_autocmds('CursorMoved', { buffer = buf })
  check(7, #marks(buf) == 0)
  check(8, vim.deep_equal(state.transcript_lines(buf), text) and api.nvim_buf_get_changedtick(buf) == tick
    and vim.bo[buf].modified == modified)
end)

it('ignores draft edits and empty placeholders; anchors streaming on an existing output line', function()
  local buf, win = open()
  state.append(buf, 'assistant', nil, '')
  state.append_text(buf, 'already read', true)
  elsewhere(win)
  local row = api.nvim_buf_line_count(buf) - 1
  state.open_draft(buf)
  api.nvim_buf_set_lines(buf, -2, -1, false, { 'draft insert', 'second draft line' })
  check(9, #marks(buf) == 0)
  state.append_text(buf, ' and unread', true)
  check(10, (marks(buf)[1] or {})[2] == row and state.draft_text(buf) == 'draft insert\nsecond draft line')
  state.append_text(buf, '\nsubsequent line', true)
  check(11, #marks(buf) == 1 and marks(buf)[1][2] == row)
end)

it('marks output while editing in the steering split and keeps it on closing the split', function()
  local buf, win = open()
  local steer = require('straps.steering').open(buf)
  api.nvim_buf_set_lines(buf, -2, -1, false, { 'unsent draft' })
  check(21, #marks(buf) == 0 and api.nvim_get_current_win() == steer)
  state.append(buf, 'assistant', nil, 'while steering')
  check(22, #marks(buf) == 1 and state.draft_text(buf) == 'unsent draft')
  api.nvim_win_close(steer, false)
  vim.wait(20, function() return false end)
  check(23, api.nvim_get_current_win() == win and #marks(buf) == 1)
end)

it('does not follow pending output from a returned cursor on the last line', function()
  local buf, win = open()
  state.append(buf, 'assistant', nil, 'already read')
  elsewhere(win)
  state.append_text(buf, ' unread', true)
  api.nvim_set_current_win(win)
  local before = view(win)
  state.append_text(buf, '\nmore', true)
  check(24, #marks(buf) == 1 and vim.deep_equal(view(win), before))
end)

it('leaves a focused copy reading and does not follow in unfocused copies', function()
  local buf, first = open()
  vim.cmd('vsplit')
  local second = api.nvim_get_current_win()
  vim.cmd('normal! Gzt')
  local before = view(first)
  state.append(buf, 'assistant', nil, 'still reading')
  check(12, #marks(buf) == 0 and vim.deep_equal(before, view(first)))
  elsewhere(second)
  state.append(buf, 'user', nil, '')
  state.append(buf, 'assistant', nil, '')
  check(13, #marks(buf) == 0)
  state.append_text(buf, 'starting a streamed response', true)
  local row = api.nvim_buf_line_count(buf) - 1
  check(14, (marks(buf)[1] or {})[2] == row)
  state.append_text(buf, '\n' .. ('later lines\n'):rep(55), true)
  api.nvim_set_current_win(first)
  vim.cmd('redraw')
  vim.cmd('normal! Gzt')
  api.nvim_exec_autocmds('WinScrolled', { pattern = tostring(first) })
  check(15, #marks(buf) == 0)
end)

it('preserves the view when returning to a hidden transcript', function()
  local buf, win = open()
  vim.cmd('normal! 15kzz')
  vim.cmd('redraw')
  local before = view(win)
  vim.cmd('enew')
  state.append(buf, 'assistant', nil, 'while hidden')
  check(19, #marks(buf) == 1 and #vim.fn.win_findbuf(buf) == 0)
  ui.show_session(buf, 'none')
  check(20, vim.deep_equal(view(win), before) and #marks(buf) == 1)
end)

it('disables and clears the decoration with render=false', function()
  local buf, win = open()
  elsewhere(win)
  state.append(buf, 'user', nil, '[straps] notice')
  check(16, #marks(buf) == 1)
  straps.setup({ render = false })
  check(17, #marks(buf) == 0)
  api.nvim_set_current_win(win)
  vim.cmd('wincmd p')
  state.append(buf, 'assistant', nil, 'disabled')
  check(18, #marks(buf) == 0)
end)
